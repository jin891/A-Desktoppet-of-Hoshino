class Settings(QMainWindow):
    sizeischanged = pyqtSignal(int)
    def __init__(self):
        super().__init__()
        self.resize(800, 600)
        self.setWindowFlags(
            Qt.WindowType.WindowStaysOnTopHint
        )
        self.WebSettingsScrollArea = QScrollArea()
        self.MainBodyScrollArea = QScrollArea()
        self.centralwidget = QWidget()
        self.setCentralWidget(self.centralwidget)
        self.setWindowTitle("设置")
        self.main_layout = QHBoxLayout()
        self.main_layout.setContentsMargins(0,0,0,0)
        self.main_layout.setSpacing(0)
        self.Tabs = QListWidget()
        self.Tabs.setFixedWidth(160)
        self.Tabs.setVerticalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAsNeeded)
        items = ["主体设置", "Web相关设置", "时间相关设置", "基础操作设置"]
        for text in items:
            item = QListWidgetItem(text)
            item.setTextAlignment(Qt.AlignmentFlag.AlignCenter)
            self.Tabs.addItem(item)
        self.MainBodySize = MainBodySettings()
        self.Websettings = Websettings()
        self.BasicSettings = BasicSettings()
        self.SleepTime = SleepTime()

        self.WebSettingsScrollArea.setWidget(self.Websettings)
        self.MainBodyScrollArea.setWidget(self.MainBodySize)

        self.MainBodySize.sizeischanged.connect(self.controlsize)
        self.stackedWidget = QStackedWidget()
        self.stackedWidget.addWidget(self.MainBodyScrollArea)
        self.stackedWidget.addWidget(self.WebSettingsScrollArea)
        self.stackedWidget.addWidget(self.SleepTime)
        self.stackedWidget.addWidget(self.BasicSettings)
        self.main_layout.addWidget(self.Tabs)
        self.main_layout.addWidget(self.stackedWidget, 1)
        self.Tabs.currentRowChanged.connect(self.stackedWidget.setCurrentIndex)
        self.Tabs.setCurrentRow(0)
        self.centralwidget.setLayout(self.main_layout)
    def controlsize(self, size: int):
        self.sizeischanged.emit(size)

